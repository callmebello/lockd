// MARK: - Projeto atual (pela janela da frente)

final class ProjectTracker {
    static let shared = ProjectTracker()
    private(set) var lastProject: String?
    private var lastDate = Date.distantPast
    private(set) var lastApp: NSRunningApplication?
    var onProjectChange: ((String) -> Void)?

    func start() {
        NSWorkspace.shared.notificationCenter.addObserver(forName: NSWorkspace.didActivateApplicationNotification, object: nil, queue: .main) { [weak self] n in
            if let app = n.userInfo?[NSWorkspace.applicationUserInfoKey] as? NSRunningApplication { self?.sample(app) }
        }
        if let f = NSWorkspace.shared.frontmostApplication { sample(f) }
    }

    static func windowTitle(pid: pid_t) -> String? {
        guard AXIsProcessTrusted() else { return nil }
        let el = AXUIElementCreateApplication(pid)
        var w: CFTypeRef?
        guard AXUIElementCopyAttributeValue(el, kAXFocusedWindowAttribute as CFString, &w) == .success, let win = w else { return nil }
        var t: CFTypeRef?
        AXUIElementCopyAttributeValue(win as! AXUIElement, kAXTitleAttribute as CFString, &t)
        return t as? String
    }

    func sample(_ app: NSRunningApplication) {
        if app.bundleIdentifier == Bundle.main.bundleIdentifier { return }
        lastApp = app
        let title = ProjectTracker.windowTitle(pid: app.processIdentifier) ?? ""
        if let p = Store.shared.matchProject(in: title) {
            let changed = p != lastProject
            lastProject = p; lastDate = Date()
            if changed { onProjectChange?(p) }
        }
    }

    /// Projeto + app de origem para o momento de uma captura.
    func current() -> (project: String?, app: String?) {
        let front = NSWorkspace.shared.frontmostApplication
        if let f = front, f.bundleIdentifier != Bundle.main.bundleIdentifier { sample(f) }
        let appName = (front?.bundleIdentifier == Bundle.main.bundleIdentifier ? lastApp : front)?.localizedName
        if let pin = Prefs.pinnedProject { return (pin, appName) }
        if let p = lastProject, Date().timeIntervalSince(lastDate) < 45 * 60 { return (p, appName) }
        return (nil, appName)
    }
}

// MARK: - Clipboard

final class ClipboardWatcher {
    var onDetect: (([Detection], String?) -> Void)?
    private var last = NSPasteboard.general.changeCount
    private var timer: Timer?
    private var suspended = false
    var ignoreCount: Int?

    static let concealed = NSPasteboard.PasteboardType("org.nspasteboard.ConcealedType")
    static let transient = NSPasteboard.PasteboardType("org.nspasteboard.TransientType")
    static let auto = NSPasteboard.PasteboardType("org.nspasteboard.AutoGeneratedType")

    func start() {
        let t = Timer.scheduledTimer(withTimeInterval: 0.45, repeats: true) { [weak self] _ in self?.tick() }
        t.tolerance = 0.3
        timer = t
        let dn = DistributedNotificationCenter.default()
        dn.addObserver(forName: .init("com.apple.screenIsLocked"), object: nil, queue: .main) { [weak self] _ in self?.suspended = true }
        dn.addObserver(forName: .init("com.apple.screenIsUnlocked"), object: nil, queue: .main) { [weak self] _ in self?.resume() }
        let wn = NSWorkspace.shared.notificationCenter
        wn.addObserver(forName: NSWorkspace.willSleepNotification, object: nil, queue: .main) { [weak self] _ in self?.suspended = true }
        wn.addObserver(forName: NSWorkspace.didWakeNotification, object: nil, queue: .main) { [weak self] _ in self?.resume() }
    }

    private func resume() { suspended = false; last = NSPasteboard.general.changeCount }

    private func tick() {
        let pb = NSPasteboard.general
        let c = pb.changeCount
        guard c != last else { return }
        last = c
        guard !suspended, !Prefs.paused, ignoreCount != c else { return }
        let types = pb.types ?? []
        if ProcessInfo.processInfo.environment["LOCKD_DEBUG"] != nil {
            NSLog("[lockd] clipboard changed: types=%@ stringLen=%d", types.map(\.rawValue).joined(separator: ","), pb.string(forType: .string)?.count ?? -1)
        }
        if types.contains(Self.concealed) || types.contains(Self.transient) || types.contains(Self.auto) { return }
        guard types.contains(.string), let s = pb.string(forType: .string) else { return }
        let dets = Detector.detect(in: s)
        guard !dets.isEmpty else { return }
        onDetect?(dets, ProjectTracker.shared.current().app)
    }
}

// MARK: - Pastas observadas (FSEvents)

final class FolderWatcher {
    var onFile: ((URL) -> Void)?
    private var stream: FSEventStreamRef?
    private var watched: Set<String> = []
    private var processed = Set<String>()
    private var sizes: [String: Int] = [:]

    func restart() {
        stop()
        var dirs: [String] = []
        let home = FileManager.default.homeDirectoryForCurrentUser
        if Prefs.watchDownloads { dirs.append(home.appendingPathComponent("Downloads").path) }
        if Prefs.watchDesktop { dirs.append(home.appendingPathComponent("Desktop").path) }
        guard !dirs.isEmpty else { return }
        watched = Set(dirs)

        var ctx = FSEventStreamContext(version: 0, info: Unmanaged.passUnretained(self).toOpaque(), retain: nil, release: nil, copyDescription: nil)
        let cb: FSEventStreamCallback = { _, info, count, paths, flags, _ in
            guard let info else { return }
            let w = Unmanaged<FolderWatcher>.fromOpaque(info).takeUnretainedValue()
            let arr = unsafeBitCast(paths, to: NSArray.self) as? [String] ?? []
            for i in 0..<count { w.handle(arr[i], flags: flags[i]) }
        }
        let fl = UInt32(kFSEventStreamCreateFlagFileEvents | kFSEventStreamCreateFlagUseCFTypes | kFSEventStreamCreateFlagNoDefer)
        guard let s = FSEventStreamCreate(nil, cb, &ctx, dirs as CFArray, FSEventStreamEventId(kFSEventStreamEventIdSinceNow), 1.0, fl) else { return }
        FSEventStreamSetDispatchQueue(s, DispatchQueue.main)
        FSEventStreamStart(s)
        stream = s
    }

    func stop() {
        guard let s = stream else { return }
        FSEventStreamStop(s); FSEventStreamInvalidate(s); FSEventStreamRelease(s)
        stream = nil
    }

    private func handle(_ path: String, flags: FSEventStreamEventFlags) {
        let f = Int(flags)
        guard f & kFSEventStreamEventFlagItemIsFile != 0,
              f & (kFSEventStreamEventFlagItemCreated | kFSEventStreamEventFlagItemRenamed) != 0 else { return }
        let url = URL(fileURLWithPath: path)
        guard watched.contains(url.deletingLastPathComponent().path), !processed.contains(path),
              FileManager.default.fileExists(atPath: path) else { return }
        if FileClassifier.classify(url).ignore { return }
        sizes[path] = -1
        settle(path, tries: 0)
    }

    /// Espera o download terminar (tamanho estável) antes de avisar.
    private func settle(_ path: String, tries: Int) {
        DispatchQueue.main.asyncAfter(deadline: .now() + 1.5) { [weak self] in
            guard let self else { return }
            let size = (try? URL(fileURLWithPath: path).resourceValues(forKeys: [.fileSizeKey]).fileSize) ?? -2
            if size < 0 { self.sizes[path] = nil; return }
            if size == self.sizes[path], size > 0 {
                self.sizes[path] = nil
                self.processed.insert(path)
                self.onFile?(URL(fileURLWithPath: path))
            } else if tries < 25 {
                self.sizes[path] = size
                self.settle(path, tries: tries + 1)
            }
        }
    }
}

// MARK: - Atalho global

final class HotKey {
    nonisolated(unsafe) private static var handlers: [UInt32: () -> Void] = [:]
    nonisolated(unsafe) private static var installed = false
    nonisolated(unsafe) private static var counter: UInt32 = 0
    private var ref: EventHotKeyRef?

    init(keyCode: UInt32, modifiers: UInt32, handler: @escaping () -> Void) {
        if !HotKey.installed {
            var spec = EventTypeSpec(eventClass: OSType(kEventClassKeyboard), eventKind: UInt32(kEventHotKeyPressed))
            InstallEventHandler(GetApplicationEventTarget(), { _, event, _ -> OSStatus in
                var hk = EventHotKeyID()
                GetEventParameter(event, EventParamName(kEventParamDirectObject), EventParamType(typeEventHotKeyID), nil,
                                  MemoryLayout<EventHotKeyID>.size, nil, &hk)
                HotKey.handlers[hk.id]?()
                return noErr
            }, 1, &spec, nil, nil)
            HotKey.installed = true
        }
        HotKey.counter += 1
        HotKey.handlers[HotKey.counter] = handler
        RegisterEventHotKey(keyCode, modifiers, EventHotKeyID(signature: 0x4C4B4431, id: HotKey.counter),
                            GetApplicationEventTarget(), 0, &ref)
    }
}

// MARK: - Clipboard de saída / colar

enum Clip {
    nonisolated(unsafe) static var watcher: ClipboardWatcher?

    static func setSecret(_ value: String) {
        let pb = NSPasteboard.general
        pb.clearContents()
        pb.declareTypes([.string, ClipboardWatcher.concealed], owner: nil)
        pb.setString(value, forType: .string)
        pb.setString("", forType: ClipboardWatcher.concealed)
        let c = pb.changeCount
        watcher?.ignoreCount = c
        let secs = Prefs.clearSeconds
        if secs > 0 {
            DispatchQueue.main.asyncAfter(deadline: .now() + .seconds(secs)) {
                if NSPasteboard.general.changeCount == c { NSPasteboard.general.clearContents() }
            }
        }
    }

    static func setText(_ s: String) {
        let pb = NSPasteboard.general
        pb.clearContents(); pb.setString(s, forType: .string)
        watcher?.ignoreCount = pb.changeCount
    }

    static func setFile(_ url: URL) {
        let pb = NSPasteboard.general
        pb.clearContents(); pb.writeObjects([url as NSURL])
        watcher?.ignoreCount = pb.changeCount
    }

    @discardableResult
    static func paste(into app: NSRunningApplication?) -> Bool {
        guard AXIsProcessTrusted() else { return false }
        app?.activate()
        DispatchQueue.main.asyncAfter(deadline: .now() + 0.14) {
            let src = CGEventSource(stateID: .combinedSessionState)
            for down in [true, false] {
                let e = CGEvent(keyboardEventSource: src, virtualKey: 9, keyDown: down)
                e?.flags = .maskCommand
                e?.post(tap: .cgAnnotatedSessionEventTap)
            }
        }
        return true
    }
}

// MARK: - Alarmes de vencimento

enum Notifier {
    static func setup() {
        guard Bundle.main.bundleIdentifier != nil else { return }
        UNUserNotificationCenter.current().requestAuthorization(options: [.alert, .sound]) { _, _ in }
        NotificationCenter.default.addObserver(forName: Store.didChange, object: nil, queue: .main) { _ in reschedule() }
        reschedule()
    }

    static func reschedule() {
        guard Bundle.main.bundleIdentifier != nil else { return }
        let c = UNUserNotificationCenter.current()
        c.removeAllPendingNotificationRequests()
        for item in Store.shared.items {
            guard let exp = item.expiresAt else { continue }
            for days in [30, 7, 1, 0] {
                guard var when = Calendar.current.date(byAdding: .day, value: -days, to: exp) else { continue }
                when = Calendar.current.date(bySettingHour: 9, minute: 0, second: 0, of: when) ?? when
                guard when > Date() else { continue }
                let content = UNMutableNotificationContent()
                content.title = days == 0 ? "\(item.name) expires today" : "\(item.name) expires in \(days) day\(days == 1 ? "" : "s")"
                content.body = [item.service, item.project].compactMap { $0 }.joined(separator: " · ")
                content.sound = .default
                let comps = Calendar.current.dateComponents([.year, .month, .day, .hour, .minute], from: when)
                c.add(UNNotificationRequest(identifier: "\(item.id.uuidString)-\(days)", content: content,
                                            trigger: UNCalendarNotificationTrigger(dateMatching: comps, repeats: false)))
            }
        }
    }
}

